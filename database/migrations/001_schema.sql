-- PostgreSQL 17; executar uma única vez em banco de desenvolvimento vazio.
BEGIN;
CREATE TABLE projetos (
    codigo text PRIMARY KEY,
    nome text NOT NULL CHECK (btrim(nome) <> '')
);
INSERT INTO projetos(codigo,nome) VALUES
    ('cdi','Clube do Improviso'), ('lab','LabSoci'), ('-','Ambos');
CREATE TABLE categorias (
    codigo text PRIMARY KEY,
    nome text NOT NULL CHECK (btrim(nome) <> '')
);
-- Valores do formulário atual (src/utils/eventos.ts), inclusive caixa de Ensaio.
INSERT INTO categorias(codigo,nome) VALUES
    ('apresentacao','Apresentação'), ('oficina','Oficina'),
    ('terca','Terça Cultural'), ('Ensaio','Ensaio');
CREATE TABLE imagens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    url text NOT NULL UNIQUE CHECK (btrim(url) <> '')
);
CREATE TABLE membros (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    nome text NOT NULL CHECK (btrim(nome) <> ''),
    foto_url text,
    funcao text NOT NULL CHECK (btrim(funcao) <> ''),
    ativo boolean NOT NULL DEFAULT true,
    matricula text
);
CREATE TABLE eventos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    nome text NOT NULL CHECK (btrim(nome) <> ''),
    data date NOT NULL CHECK (isfinite(data)),
    hora time(0),
    local text NOT NULL DEFAULT 'Sala dos Projetos Culturais' CHECK (btrim(local) <> ''),
    descr text,
    descr_g text,
    capa_id integer REFERENCES imagens(id) ON DELETE RESTRICT,
    proj text NOT NULL DEFAULT '-' REFERENCES projetos(codigo),
    categoria text REFERENCES categorias(codigo),
    concluido boolean NOT NULL DEFAULT false,
    entrada text
);
CREATE TABLE evento_membro (
    evento_id integer NOT NULL REFERENCES eventos(id) ON DELETE CASCADE,
    membro_id integer NOT NULL REFERENCES membros(id) ON DELETE RESTRICT,
    PRIMARY KEY (evento_id, membro_id)
);
CREATE TABLE evento_imagem (
    evento_id integer NOT NULL REFERENCES eventos(id) ON DELETE CASCADE,
    imagem_id integer NOT NULL REFERENCES imagens(id) ON DELETE RESTRICT,
    PRIMARY KEY (evento_id, imagem_id)
);
CREATE TABLE evento_tag (
    evento_id integer NOT NULL REFERENCES eventos(id) ON DELETE CASCADE,
    tag text NOT NULL CHECK (btrim(tag) <> ''),
    PRIMARY KEY (evento_id, tag)
);
CREATE INDEX eventos_data_idx ON eventos(data, id);
CREATE INDEX eventos_capa_idx ON eventos(capa_id);
CREATE INDEX eventos_proj_idx ON eventos(proj);
CREATE INDEX eventos_categoria_idx ON eventos(categoria);
CREATE INDEX membros_nome_idx ON membros(nome, id);
CREATE INDEX evento_membro_membro_idx ON evento_membro(membro_id);
CREATE INDEX evento_imagem_imagem_idx ON evento_imagem(imagem_id);
-- Compatibilidade com os contratos JSON consumidos pelo React (datas sem fuso).
CREATE VIEW eventos_api AS
    SELECT e.id,e.nome,to_char(e.data,'YYYY-MM-DD') AS data,
           e.local,e.hora::text AS hora,e.descr,e.descr_g,i.url AS capa_url,
           e.proj,e.categoria,e.concluido,e.entrada
    FROM eventos e LEFT JOIN imagens i ON i.id = e.capa_id;
COMMIT;
